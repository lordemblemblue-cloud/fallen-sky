#!/usr/bin/env node
/* global process, console */
// Turns the owner's "Ancient Sumi-e Corridor & Cavern 3D Viewer" page into a
// module the game can build from: the two classes that make the materials and
// the five pieces, without the page, the renderer, the camera or the buttons.
//
// The owner's builder code is copied as it is. Only the viewer-only methods
// are left out, and the page's global THREE and document become parameters.
//
// Usage: node scripts/extract-sumi-corridor-kit.mjs <viewer.html> [out.js]
import fs from 'node:fs';
import path from 'node:path';

const [input,output='src/components/game3d/wolfveil/caves/SumiCorridorKit.js']=process.argv.slice(2);
if(!input){console.error('Give the path of the corridor viewer page.');process.exit(1);}
const page=fs.readFileSync(input,'utf8').replace(/\r\n/g,'\n');
const lines=page.split('\n');
const find=(text,from=0)=>{const i=lines.findIndex((line,n)=>n>=from&&line.startsWith(text));
  if(i<0)throw new Error('Not found in the page: '+text);return i;};
const factoryStart=find('class ProceduralArtFactory {');
const appStart=find('class SumiCorridorApp {',factoryStart);
const pageStart=find('window.onload',appStart);
const classEnd=(()=>{for(let i=pageStart-1;i>appStart;i--)if(lines[i]==='}')return i;throw new Error('No end of class');})();

// Methods that only serve the viewer page.
const VIEWER_ONLY=new Set(['constructor','initScene','initLighting','setViewMode','focusSanctuaryPOI','bindEvents','animate']);
const app=[];
let skipping=false,dropped=[];
for(let i=appStart+1;i<classEnd;i++){
  const line=lines[i],method=/^ {4}([A-Za-z_][A-Za-z0-9_]*)\(.*\) \{$/.exec(line);
  if(method&&VIEWER_ONLY.has(method[1])){skipping=true;dropped.push(method[1]);continue;}
  if(skipping){if(line==='    }')skipping=false;continue;}
  app.push(line);
}
// A comment block left directly above a removed method goes with it.
const title=(/<title>([^<]*)<\/title>/.exec(page)||[])[1]||'corridor viewer';
const kit=`// GENERATED by scripts/extract-sumi-corridor-kit.mjs from the owner's page
// "${title}" (${path.basename(input)}).
// Do not edit by hand: change the page, or the script, and extract again.
//
// The owner's own builder code, as written: the procedural materials and the
// five pieces (two hallways, the T-junction, the cave and canyon, the sunken
// sanctuary). The viewer page's renderer, camera, lights and buttons are left
// out (${dropped.join(', ')}).
//
// The pieces are far too heavy to hand to the renderer as they are (one mesh
// per brick). WolfveilSumiCaveBake.mjs turns a piece into a few merged
// batches before the game draws it.

/**
 * @param THREE the game's Three.js
 * @param document where canvases for the painted textures come from
 * @returns the builder: materials are ready, no piece is built yet.
 *   Call createHallwayStandaloneModule(), createHallwayAttachedModule(),
 *   createDetachedTJunctionModule(), createDetachedCaveCanyonModule() or
 *   createDetachedSunkenSanctuaryCaveModule(); each returns a THREE.Group.
 */
export function createSumiCorridorKit({THREE,document}){
${lines.slice(factoryStart,appStart).join('\n').trimEnd()}

class SumiCorridorApp {
    constructor() {
        this.artFactory = new ProceduralArtFactory();
        this.secretOpen = false;
        this.torchLights = [];
        this.magicObjects = [];
        this.waterMeshes = [];
        this.gyroRings = [];
        this.waterfallColumns = [];
        this.scene = new THREE.Group();
        this.initMaterials();
    }

${app.join('\n').trimEnd()}
}
  return new SumiCorridorApp();
}
`;
fs.mkdirSync(path.dirname(output),{recursive:true});
fs.writeFileSync(output,kit);
console.log(output+': '+kit.split('\n').length+' lines; left out '+dropped.join(', '));
